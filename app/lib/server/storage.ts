import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

// File storage behind a small interface, so the backend can move to a bucket (S3, Cloudflare R2,
// Supabase Storage...) by adding a driver here, without touching the routes.
//
// Today's driver writes to a folder on the server's disk: STORAGE_DIR, default ./storage at the
// project root (git-ignored). Files are never served straight from that folder; they go through
// API routes that check who's asking. Hosts with a temporary disk (Vercel, most containers) lose
// these files on redeploy, so use a bucket driver there.

export interface StoredFile {
  body: Buffer;
  contentType: string;
}

interface StorageDriver {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredFile | null>;
  delete(key: string): Promise<void>;
}

// Keys are generated by the server (folder/uuid.ext). This guard keeps any key from ever
// resolving outside the storage folder.
const KEY_RE = /^[a-z0-9-]+(?:\/[a-z0-9-]+)*\.[a-z0-9]+$/;

function assertKey(key: string) {
  if (!KEY_RE.test(key)) throw new Error(`Invalid storage key: ${key}`);
}

const CONTENT_TYPES: Record<string, string> = { webp: 'image/webp', jpg: 'image/jpeg', png: 'image/png' };

function localDriver(root: string): StorageDriver {
  const file = (key: string) => {
    assertKey(key);
    const full = path.resolve(root, key);
    if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error('Storage key escapes the storage folder');
    return full;
  };
  return {
    async put(key, body) {
      const full = file(key);
      await mkdir(path.dirname(full), { recursive: true });
      await writeFile(full, body);
    },
    async get(key) {
      try {
        const body = await readFile(file(key));
        return { body, contentType: CONTENT_TYPES[key.split('.').pop()!] ?? 'application/octet-stream' };
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
        throw e;
      }
    },
    async delete(key) {
      await rm(file(key), { force: true });
    },
  };
}

const globalForStorage = globalThis as unknown as { storage?: StorageDriver };

export function storage(): StorageDriver {
  globalForStorage.storage ??= localDriver(path.resolve(process.env.STORAGE_DIR ?? 'storage'));
  return globalForStorage.storage;
}

/** Deletes files without failing the request; a leftover file is better than a failed delete. */
export async function deleteQuietly(...keys: (string | null | undefined)[]) {
  await Promise.all(
    keys.filter((k): k is string => !!k).map((k) => storage().delete(k).catch((e) => console.error('[storage] delete failed', k, e))),
  );
}
